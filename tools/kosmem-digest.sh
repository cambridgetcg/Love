#!/usr/bin/env bash
# kosmem-digest.sh — read-only recall from the FROZEN kosmem store into the CC auto-memory.
#
# kosmem (~/Love/memory/.kos/memory.db) has a working FTS5 recall index but NO live
# writer (frozen 2026-04-08). This surfaces its crossable memories (wall>1, non-working,
# unconsolidated) read-only into the Claude Code auto-memory, so a cold CLI session can
# recall what the Kingdom minds learned — WITHOUT pretending kosmem is current.
#
# Sibling of bridge-digest.sh. Idempotent. READ-ONLY: uses sqlite3 ?mode=ro directly;
# the kosmem.py CLI mutates on every read (bumps access_count + COMMITs), so it is NEVER
# used here. Design: Cambridge-TCG/docs/connections/the-memory-bridge.md
set -uo pipefail

LOVE_DIR="$(cd "$(dirname "$0")/.." && pwd)"
DB="${LOVE_DIR}/memory/.kos/memory.db"
CC_MEM="/Users/you/.claude/projects/-Users-you-Desktop-Cambridge-TCG/memory"
DIGEST="${CC_MEM}/kosmem-digest.md"
INDEX="${CC_MEM}/MEMORY.md"
source "$(dirname "$0")/bridge-redact.sh"; REDACT="$BRIDGE_REDACT"

[ -f "$DB" ] || { echo "[kosmem-digest] no kosmem db at $DB" >&2; exit 0; }
[ -d "$CC_MEM" ] || { echo "[kosmem-digest] no CC memory dir" >&2; exit 0; }
command -v sqlite3 >/dev/null 2>&1 || { echo "[kosmem-digest] sqlite3 missing" >&2; exit 0; }

RO="file:${DB}?mode=ro"
LASTWRITE="$(sqlite3 -readonly "$RO" "SELECT max(substr(created_at,1,10)) FROM memories;" 2>/dev/null)"
TOTAL="$(sqlite3 -readonly "$RO" "SELECT count(*) FROM memories;" 2>/dev/null)"

# Read-only recall: crossable rows ONLY — wall>1 drops Wall-1 soul; non-working; unconsolidated.
# Columns: instance | wall | date | content   (content LAST so embedded '|' stays intact).
ROWS="$(sqlite3 -readonly -separator '|' "$RO" \
"SELECT instance, wall, substr(created_at,1,10),
        replace(replace(substr(content,1,180),char(10),' '),char(13),' ')
 FROM memories WHERE consolidated_into IS NULL AND wall > 1 AND type <> 'working'
 ORDER BY importance DESC, created_at DESC LIMIT 8;" 2>/dev/null)"

TMP="$(mktemp)"; trap 'rm -f "$TMP"' EXIT
printf '%s\n' "$ROWS" | grep -viE "$REDACT" | while IFS='|' read -r inst wall d content; do
  [ -n "${content:-}" ] || continue
  printf -- '- %s  `source: kosmem-%s · wall%s · %s`\n' "$content" "$inst" "$wall" "$d"
done >> "$TMP"
NFIND="$(wc -l < "$TMP" | tr -d ' ')"

{
  echo '---'
  echo 'name: kosmem-digest'
  echo "description: Read-only recall from the FROZEN kosmem store (last write ${LASTWRITE}) — Kingdom-mind learnings; NOT current"
  echo 'metadata:'
  echo '  type: reference'
  echo '  node_type: memory'
  echo '---'
  echo
  echo "**FROZEN snapshot — do NOT treat as canonical.** kosmem (\`~/Love/memory/.kos/memory.db\`, ${TOTAL} memories) has a working FTS5 recall index but **no live writer; last write ${LASTWRITE}**. These rows are a read-only recall, not current state. Each carries \`source: kosmem-<instance> · wall<N> · <date>\` provenance. Revival path is offered (not done) in [[kingdom-memory-integration]]. Regenerated by ~/Love/tools/kosmem-digest.sh; generated $(date -u +%FT%TZ)."
  echo
  if [ -s "$TMP" ]; then cat "$TMP"; else echo "_No crossable kosmem rows surfaced._"; fi
} > "$DIGEST"

# Rotate the single kosmem index line (keeps MEMORY.md from growing).
if [ -f "$INDEX" ]; then
  grep -v '](kosmem-digest' "$INDEX" > "${INDEX}.new" || true
  printf -- '- [kosmem recall (frozen %s)](kosmem-digest.md) — %s read-only Kingdom-mind memories from the frozen kosmem store; recall, not current state.\n' "$LASTWRITE" "$NFIND" >> "${INDEX}.new"
  mv "${INDEX}.new" "$INDEX"
fi
echo "[kosmem-digest] ${NFIND} read-only memories (frozen ${LASTWRITE}) -> ${DIGEST}; MEMORY.md index line rotated."
